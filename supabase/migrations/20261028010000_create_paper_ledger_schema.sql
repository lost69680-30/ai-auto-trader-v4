BEGIN;

-- Keep paper-trading state outside Supabase's exposed public schema/Data API.
CREATE SCHEMA IF NOT EXISTS paper_ledger;
REVOKE ALL ON SCHEMA paper_ledger FROM PUBLIC;

CREATE TABLE IF NOT EXISTS paper_ledger.paper_orders (
    proposal_id text PRIMARY KEY,
    signal_id text NOT NULL,
    symbol text NOT NULL,
    side text NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    quantity double precision NOT NULL CHECK (quantity > 0),
    entry_price double precision NOT NULL CHECK (entry_price > 0),
    stop_loss double precision NOT NULL CHECK (stop_loss > 0),
    take_profit double precision NOT NULL CHECK (take_profit > 0),
    recorded_at double precision NOT NULL,
    status text NOT NULL CHECK (status IN ('PENDING_PAPER_SIMULATION', 'FILLED', 'CLOSED'))
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_fills (
    fill_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id text NOT NULL UNIQUE REFERENCES paper_ledger.paper_orders(proposal_id),
    symbol text NOT NULL,
    side text NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    quantity double precision NOT NULL CHECK (quantity > 0),
    market_price double precision NOT NULL CHECK (market_price > 0),
    fill_price double precision NOT NULL CHECK (fill_price > 0),
    fee double precision NOT NULL CHECK (fee >= 0),
    fee_rate double precision NOT NULL CHECK (fee_rate >= 0),
    slippage_bps double precision NOT NULL CHECK (slippage_bps >= 0),
    filled_at double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_positions (
    proposal_id text PRIMARY KEY REFERENCES paper_ledger.paper_orders(proposal_id),
    symbol text NOT NULL,
    side text NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    quantity double precision NOT NULL CHECK (quantity > 0),
    entry_price double precision NOT NULL CHECK (entry_price > 0),
    mark_price double precision NOT NULL CHECK (mark_price > 0),
    stop_loss double precision NOT NULL CHECK (stop_loss > 0),
    take_profit double precision NOT NULL CHECK (take_profit > 0),
    opened_at double precision NOT NULL,
    mark_observed_at double precision NOT NULL,
    status text NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    opening_fee double precision NOT NULL CHECK (opening_fee >= 0),
    closing_fee double precision NOT NULL DEFAULT 0 CHECK (closing_fee >= 0),
    funding_pnl double precision NOT NULL DEFAULT 0,
    realized_pnl double precision,
    closed_at double precision,
    close_price double precision,
    close_market_price double precision,
    close_fee_rate double precision,
    close_slippage_bps double precision
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_funding_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funding_id text NOT NULL UNIQUE,
    proposal_id text NOT NULL REFERENCES paper_ledger.paper_positions(proposal_id),
    symbol text NOT NULL,
    funding_rate double precision NOT NULL,
    mark_price double precision NOT NULL CHECK (mark_price > 0),
    amount double precision NOT NULL,
    occurred_at double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_audit_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type text NOT NULL,
    proposal_id text,
    occurred_at double precision NOT NULL,
    payload_json text NOT NULL
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_system_controls (
    control_key text PRIMARY KEY,
    active integer NOT NULL CHECK (active IN (0, 1)),
    updated_at double precision NOT NULL,
    reason text NOT NULL,
    activated_at double precision
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_order_cancellations (
    proposal_id text PRIMARY KEY REFERENCES paper_ledger.paper_orders(proposal_id),
    cancelled_at double precision NOT NULL,
    reason text NOT NULL
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_position_extrema (
    proposal_id text PRIMARY KEY REFERENCES paper_ledger.paper_positions(proposal_id),
    high_water double precision NOT NULL CHECK (high_water > 0),
    low_water double precision NOT NULL CHECK (low_water > 0)
);

CREATE TABLE IF NOT EXISTS paper_ledger.paper_equity_snapshots (
    snapshot_at double precision PRIMARY KEY CHECK (snapshot_at >= 0),
    account_equity double precision NOT NULL,
    high_water_equity double precision NOT NULL,
    drawdown_amount double precision NOT NULL CHECK (drawdown_amount >= 0),
    drawdown_pct double precision NOT NULL CHECK (drawdown_pct >= 0),
    unrealized_pnl double precision NOT NULL,
    open_position_count integer NOT NULL CHECK (open_position_count >= 0),
    oldest_mark_age_seconds double precision NOT NULL CHECK (oldest_mark_age_seconds >= 0),
    marks_fresh integer NOT NULL CHECK (marks_fresh IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_paper_funding_proposal ON paper_ledger.paper_funding_events(proposal_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_paper_orders_status ON paper_ledger.paper_orders(status);
CREATE INDEX IF NOT EXISTS idx_paper_positions_status ON paper_ledger.paper_positions(status);
CREATE INDEX IF NOT EXISTS idx_paper_audit_proposal ON paper_ledger.paper_audit_events(proposal_id);

-- Enable RLS for defense in depth and grant no access through public API roles.
ALTER TABLE paper_ledger.paper_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_fills ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_positions ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_funding_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_audit_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_system_controls ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_order_cancellations ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_position_extrema ENABLE ROW LEVEL SECURITY;
ALTER TABLE paper_ledger.paper_equity_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA paper_ledger FROM PUBLIC;

DO $$
DECLARE
    role_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON SCHEMA paper_ledger FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA paper_ledger FROM %I', role_name);
        END IF;
    END LOOP;
END
$$;

COMMIT;